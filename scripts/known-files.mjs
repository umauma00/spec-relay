#!/usr/bin/env node
// The files earlier spec-relay versions installed in a repository being
// migrated: the schemas (openspec-schemas/) and the files that pin OpenSpec
// (templates/openspec-tools/). setup.mjs replaces a file in the repository
// with this kit's version only when its content is one of these, so a kit
// update needs no manual deletes, and a file someone edited is still a conflict.
//
// known-files.json maps each kit path to the SHA-256 of every content it has
// had (CRLF and a BOM ignored, JSON compared parsed). Run this script in the kit
// repository after changing a schema or the pinned OpenSpec; a test fails until
// the current contents are listed.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const KIT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const KNOWN_FILE = path.join(KIT_ROOT, 'scripts/known-files.json');
export const TRACKED = ['openspec-schemas', 'templates/openspec-tools'];

// The same text whatever the checkout did to it (as setup.mjs normalizeText).
const normalize = (text) => text.replace(/^﻿/, '').replace(/\r\n/g, '\n');
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map((k) => [k, sortKeys(value[k])]));
}

// A reformatted JSON file is the same file; unparsable JSON is hashed as text.
export function contentHash(rel, text) {
  let canonical = normalize(text);
  if (rel.endsWith('.json')) {
    try { canonical = JSON.stringify(sortKeys(JSON.parse(canonical))); } catch { /* hashed as text */ }
  }
  return crypto.createHash('sha256').update(canonical, 'utf8').digest('hex');
}

let cache;
export function knownFiles() {
  if (!cache) {
    try { cache = JSON.parse(fs.readFileSync(KNOWN_FILE, 'utf8')).files || {}; } catch { cache = {}; }
  }
  return cache;
}

// Whether text is a content the kit file at rel (posix, from the kit root) has had.
export function isKnown(rel, text) {
  const hashes = knownFiles()[rel];
  return Array.isArray(hashes) && hashes.includes(contentHash(rel, text));
}

const git = (args) => {
  const result = spawnSync('git', args, { cwd: KIT_ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${(result.stderr || '').trim()}`);
  return result.stdout;
};

function listFiles(dir, base = dir) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return []; }
  return entries.flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? listFiles(full, base) : [path.relative(base, full).replace(/\\/g, '/')];
  });
}

// Every content of the tracked files in the kit's git history, plus the working tree.
export function collect() {
  if (git(['rev-parse', '--is-shallow-repository']).trim() === 'true') {
    throw new Error('the kit repository is a shallow clone; run git fetch --unshallow first');
  }
  const files = {};
  const add = (rel, text) => { (files[rel] ??= new Set()).add(contentHash(rel, text)); };
  const blobs = new Map();
  for (const commit of git(['rev-list', 'HEAD', '--', ...TRACKED]).split('\n').filter(Boolean)) {
    for (const line of git(['ls-tree', '-r', commit, '--', ...TRACKED]).split('\n').filter(Boolean)) {
      const [meta, rel] = line.split('\t');
      const blob = meta.split(' ')[2];
      if (!blobs.has(blob)) blobs.set(blob, new Set());
      blobs.get(blob).add(rel);
    }
  }
  for (const [blob, rels] of blobs) {
    const text = git(['cat-file', 'blob', blob]);
    for (const rel of rels) add(rel, text);
  }
  for (const top of TRACKED) {
    for (const rel of listFiles(path.join(KIT_ROOT, top))) add(`${top}/${rel}`, fs.readFileSync(path.join(KIT_ROOT, top, rel), 'utf8'));
  }
  return Object.fromEntries(Object.keys(files).sort().map((rel) => [rel, [...files[rel]].sort()]));
}

function invokedDirectly() {
  if (!process.argv[1]) return false;
  try { return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url)); } catch { return false; }
}

if (invokedDirectly()) {
  try {
    const files = collect();
    const note = 'Generated by scripts/known-files.mjs: SHA-256 of every content each kit file has had. setup.mjs replaces a file in this list without asking.';
    fs.writeFileSync(KNOWN_FILE, `${JSON.stringify({ note, files }, null, 1)}\n`);
    console.log(`wrote ${path.relative(KIT_ROOT, KNOWN_FILE)} (${Object.keys(files).length} files, ${Object.values(files).reduce((n, h) => n + h.length, 0)} contents)`);
  } catch (error) {
    console.error(`known-files: ${error.message}`);
    process.exitCode = 1;
  }
}
